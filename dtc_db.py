def _system(code):
    for lo, hi, name in SYSTEM_RANGES:
        if lo <= code <= hi:
            return name
    if code[0] == "P":
        return SYSTEM_P.get(code[2], "Двигатель и трансмиссия")
    return LETTER.get(code[0], "")


def describe_obd(code, make=None):
    code = code.upper()
    system = _system(code)
    if code in OBD:
        desc, sev = OBD[code]
        return {"description": desc, "severity": sev, "system": system, "hint": HINTS.get(code, "")}
    maker = code[1] == "1" or (code[0] == "P" and code[1] == "3" and code[2] in "0123") \
        or (code[0] in "BCU" and code[1] in "12")
    if maker:
        src = (make or "").strip() or "производителя"
        desc = f"Код производителя ({system}). Точную расшифровку смотрите в сервисной документации {src} по этому коду."
    else:
        desc = f"Общий код SAE, система: {system}. Нет в локальной базе — пришлите код, добавлю расшифровку."
    return {"description": desc, "severity": "medium", "system": system, "hint": ""}


